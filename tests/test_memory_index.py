"""The memory index is generated, and the gate refuses a stale one - ballot P2/A2, carried 5-0.

Forge-22 measured a seat's read-first load at ~36k tokens a session. A1 shrank STATUS.md; A2 is
this index, so a seat reads one small table and pulls only the documents its task needs. Three
seats attached one condition: the index must be regenerated by the same gate that runs the suite,
because a stale index is worse than none - seats would trust it. `test_the_index_matches_the_generator`
plus the pre-push step is that condition.
"""

from pathlib import Path

from megazword import memory_index

DOCS = Path(__file__).resolve().parents[1] / "docs"


def _seed(tmp_path: Path, *names: str) -> Path:
    for name in names:
        (tmp_path / name).write_text(f"# {name}\n\nsome words\n", encoding="utf-8")
    return tmp_path


def test_the_index_lists_every_memory_file_but_not_archives(tmp_path):
    _seed(tmp_path, "STATUS.md", "SPEC.md", "ZZZ-LATER.md", "STATUS-ARCHIVE.md",
          "ARCHIVE.md", "MEMORY-INDEX.md")
    listed = {path.name for path in memory_index.files(tmp_path)}
    assert listed == {"STATUS.md", "SPEC.md", "ZZZ-LATER.md"}


def test_read_order_comes_first_then_alphabetical(tmp_path):
    _seed(tmp_path, "SPEC.md", "AAAA.md", "STATUS.md", "ZZZZ.md")
    names = [path.name for path in memory_index.files(tmp_path)]
    assert names[0] == "STATUS.md"          # read-order first
    assert names[1:] == ["SPEC.md", "AAAA.md", "ZZZZ.md"] or names[1] == "SPEC.md"
    assert names[-1] == "ZZZZ.md"


def test_each_line_has_a_size_and_a_load_when(tmp_path):
    _seed(tmp_path, "STATUS.md", "ODD-ONE.md")
    text = memory_index.render(tmp_path)
    assert "| `docs/STATUS.md` |" in text
    assert "kB | always" in text                     # known file: specific trigger
    assert "when your task names it" in text          # unknown file: honest default
    assert "ODD-ONE.md" in text


def test_write_is_idempotent_and_reports_change(tmp_path):
    _seed(tmp_path, "STATUS.md")
    assert memory_index.write(tmp_path) is True
    assert memory_index.stale(tmp_path) is False
    assert memory_index.write(tmp_path) is False      # same bytes -> no change


def test_the_rendering_is_byte_stable(tmp_path):
    """A timestamp would rewrite the file on every run and defeat the cached prompt prefix."""
    _seed(tmp_path, "STATUS.md", "DECISIONS.md")
    assert memory_index.render(tmp_path) == memory_index.render(tmp_path)


def test_the_index_matches_the_generator():
    """The enforcement. If this fails, someone edited the index by hand or changed a doc."""
    expected = memory_index.render(DOCS)
    actual = (DOCS / memory_index.INDEX_NAME).read_text(encoding="utf-8")
    assert actual == expected, (
        "docs/MEMORY-INDEX.md is out of date; run `megazword index --write` and commit the result")
