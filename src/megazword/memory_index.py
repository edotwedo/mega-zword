"""The memory index: what is in `docs/`, and when to load it.

Ballot P2 item A2, carried 5-0 (2026-10-21). Forge-22 measured a seat's read-first load at
~36k tokens a session; the fix is to read one small index and pull only the documents a task
actually needs, instead of loading every memory file on faith.

The index is **generated, never hand-edited**. `megazword index --write` renders
`docs/MEMORY-INDEX.md`; the land-gate regenerates it and refuses a push that would change it,
and a test asserts it matches - so it cannot go stale, which three seats insisted on, because
a stale index is worse than none when seats trust it.

The output carries no timestamp on purpose: unchanged input must render byte-identical bytes,
so a seat re-reading it hits the provider's cached rate, not a fresh one.
"""

from __future__ import annotations

import argparse
from pathlib import Path

DOCS = Path(__file__).resolve().parents[2] / "docs"
INDEX_NAME = "MEMORY-INDEX.md"

# Never indexed: the index itself, and the two append-only archives nobody reads at startup.
# They exist to be grepped on the rare day a task needs history, not to be loaded.
SKIP = frozenset({INDEX_NAME, "STATUS-ARCHIVE.md", "ARCHIVE.md"})

# Read order first, then the rest alphabetically. A seat that follows the index opens
# STATUS.md always and nothing else until its "load when" line matches the task.
FIRST = ("STATUS.md", "SPEC.md", "DECISIONS.md", "HIVE-ROSTER.md", "SYSTEM-DRAFT.md", "FLOOR.md")

# When to open each file. Keep these specific: a vague line ("read when relevant") makes a
# seat load everything, which is the exact cost this index exists to remove.
LOAD_WHEN = {
    "STATUS.md": "always - current state and the exact next step",
    "SPEC.md": "when the task changes what we are building, or a decision behind it",
    "DECISIONS.md": "when you are changing or questioning a past choice with Phil",
    "HIVE-ROSTER.md": "when you need a seat's role, window or designation shape",
    "SYSTEM-DRAFT.md": "when you are writing or changing a rule (needs a ballot first)",
    "FLOOR.md": "when you are working the floor: seats, claims, the conductor",
    "AGENT-ACCESS.md": "when wiring a new AI CLI into the Hive",
    "ANDROID-HIVE.md": "when the work touches the phone or the Android build",
    "BUSINESS-MODEL.md": "when the task is pricing or how the product earns",
    "BUSINESS-PLAN.md": "when the task is the plan to make money",
    "CLOUD-ROOM.md": "when the task touches the Worker, the room protocol or Discord",
    "CMDC-OWNERSHIP.md": "when ownership or the usage meter is in question",
    "FEATURES.md": "when you are adding a user-facing feature",
    "FREE-MODEL-ROSTER.md": "when picking a free model or provider",
    "GUIDE.md": "when writing user-facing documentation",
    "HIVE-RECOVERY.md": "when a seat is dead, wedged or needs respawning",
    "INSPIRATION.md": "when you need direction on what this is for",
    "INSPIRATION-ROADMAP.md": "when sequencing ideas into work",
    "LANDING-PAGE.md": "when the task touches the public page",
    "LINUX.md": "when installing or running Mega Zword on Linux",
    "PHIL-SETUP-MAP.md": "when setting up Phil's machine or the launchers",
    "PRODUCTS.md": "when the task is about what we sell",
    "PROVIDER-TERMS.md": "before automating a provider or changing access",
    "QUEUE.md": "when adding or reading a Night Shift job",
    "RELEASE-NOTES.md": "when preparing a release",
    "REPO-MAP.md": "when you need to find code without reading all of it",
    "REVENUE-OS.md": "when the task is the revenue operating system",
    "ROADMAP.md": "when choosing what to build next",
    "ROUTING_RESEARCH.md": "when the task is model routing",
}
LOAD_WHEN_DEFAULT = "when your task names it, or changes what it describes"


def _load_when(name: str) -> str:
    return LOAD_WHEN.get(name, LOAD_WHEN_DEFAULT)


def files(docs: Path | None = None) -> list[Path]:
    """Every memory document, read-order first then alphabetical, archives excluded."""
    root = docs or DOCS
    found = {p.name: p for p in root.glob("*.md") if p.name not in SKIP}
    ordered = [found.pop(name) for name in FIRST if name in found]
    ordered += [found[name] for name in sorted(found)]
    return ordered


def _size(path: Path) -> str:
    # Size with line endings normalised to LF, so a CRLF (Windows) checkout and an LF
    # checkout produce the same index. stat().st_size made the index flip between seats.
    data = path.read_bytes().replace(b"\r\n", b"\n")
    return f"{len(data) / 1024:.1f} kB"


def render(docs: Path | None = None) -> str:
    """The full index text. Deterministic: same files, same bytes."""
    root = docs or DOCS
    lines = [
        "# Memory index",
        "",
        "Generated by `megazword index --write` (ballot P2/A2, carried 5-0). Do not edit by hand:",
        "the land-gate regenerates this file and refuses a push that would change it.",
        "",
        "Read `docs/STATUS.md` always. Open another file only when its **load when** matches your",
        "task - loading everything is what this index exists to stop. Archives are grepped, never read.",
        "",
        "| File | Size | Load when |",
        "| --- | --- | --- |",
    ]
    for path in files(root):
        rel = f"docs/{path.name}"
        lines.append(f"| `{rel}` | {_size(path)} | {_load_when(path.name)} |")
    lines.append("")
    return "\n".join(lines)


def index_path(docs: Path | None = None) -> Path:
    return (docs or DOCS) / INDEX_NAME


def write(docs: Path | None = None) -> bool:
    """Write the index. True if it changed, False if it was already current."""
    target = index_path(docs)
    text = render(docs)
    if target.exists() and target.read_text(encoding="utf-8") == text:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return True


def stale(docs: Path | None = None) -> bool:
    target = index_path(docs)
    return not target.exists() or target.read_text(encoding="utf-8") != render(docs)


def command(args) -> int:
    docs = getattr(args, "path", None)
    if getattr(args, "write", False):
        changed = write(docs)
        words = "regenerated" if changed else "already current"
        print(f"[megazword index] {index_path(docs).name} {words}")
        return 0
    print(render(docs), end="")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate docs/MEMORY-INDEX.md")
    parser.add_argument("--path", type=Path, help="a docs directory to index instead")
    return command(parser.parse_args(argv))


def add_parser(sub) -> None:
    parser = sub.add_parser("index", help="memory index: what is in docs/, and when to load it")
    parser.add_argument("--write", action="store_true", help="regenerate docs/MEMORY-INDEX.md")
    parser.add_argument("--path", type=Path, help="a docs directory to index instead")


if __name__ == "__main__":
    raise SystemExit(main())
