#!/bin/sh
# Put the Hive's CLI windows back exactly as they were.
#
#   scripts/hive_resume.sh                 restore the layout (opens the windows)
#   scripts/hive_resume.sh --only Gavin-27  reopen just one seat
#   scripts/hive_resume.sh --print-only    show what would open; open nothing
#   scripts/hive_resume.sh --install-hook  restore on every reboot (Omarchy post-boot hook)
#
# The layout comes from scripts/hive_snapshot.py. One SEATLESS kitty is started, purely to own a
# remote-control socket, and then EVERY seat is added with
# `kitten @ launch --type=tab|os-window --env MEGAZWORD_SEAT=<seat>` - which is what gives each
# tab its own identity instead of inheriting one shared variable (the bug of 2026-10-26: five
# windows, all Gavin-27). The host is a seatless `sleep` on purpose: `kitty -e <cmd>` exits when
# <cmd> exits and the socket dies with it, so a seat riding in the host could take the whole
# restore down. The host tab is closed afterwards, and the restore then COUNTS the seats that
# actually came up and logs the count.
#
# A kitty session file would have been the natural fit and does not work: kitty 0.49.2 calls
# the whole session invalid when it contains `launch --title` or `launch --env`. Details and
# the other dead ends are in the snapshot script's docstring.
#
# Ghostty is the fallback when kitty is absent: it can open windows but has no CLI action for
# tabs, so the seats and their conversations come back and only the grouping is lost.
set -eu

repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
python=${MZ_PYTHON:-$repo/.venv/bin/python}
[ -x "$python" ] || python=python3

snapshot="$repo/scripts/hive_snapshot.py"
layout_file="${HOME}/.megazword/hive-layout.json"
socket="${XDG_RUNTIME_DIR:-/tmp}/kitty-hive.sock"
marker="${HOME}/.megazword/hive-restore.boot"

mode=restore
only=
while [ "$#" -gt 0 ]; do
  case "$1" in
    --only)
      [ "$#" -ge 2 ] && [ -n "$2" ] || { echo "--only needs a designation" >&2; exit 2; }
      only=$2
      shift
      ;;
    --print-only) mode=print ;;
    --install-hook) mode=hook ;;
    --help|-h) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

if [ "$mode" = hook ]; then
  # Omarchy runs ~/.config/omarchy/hooks/post-boot.d/* once the desktop is up, which is
  # exactly "after every reboot" on this box.
  #
  # `omarchy hook install` COPIES the file and names the copy after it. Installing this script
  # directly would therefore freeze a snapshot of it - the restore would quietly stop matching
  # this repo - and installing under a temporary name would add a second hook beside the old
  # copy, so the restore would run twice. Write the wrapper under its real name instead.
  tmpdir=$(mktemp -d)
  cat > "$tmpdir/hive_resume.sh" <<EOF
#!/bin/sh
# Generated by $0 --install-hook. Runs the repo's restore so this hook cannot go stale.
exec "$repo/scripts/hive_resume.sh"
EOF
  chmod +x "$tmpdir/hive_resume.sh"
  omarchy hook install post-boot "$tmpdir/hive_resume.sh"
  rm -rf "$tmpdir"
  echo "installed: post-boot hook -> $repo/scripts/hive_resume.sh"
  exit 0
fi

# A single-seat replacement must work after the boot restore and must not disturb
# that restore's socket or saved layout.
set --
if [ -n "$only" ]; then
  set -- --only "$only"
  socket="${XDG_RUNTIME_DIR:-/tmp}/kitty-hive-$$.sock"
  export MZ_HIVE_SOCKET="$socket"
fi

# Snapshot now, so a restore always replays the current layout rather than a stale one.
if [ -n "$only" ]; then
  "$python" "$snapshot" "$@" --print >/dev/null
else
  "$python" "$snapshot" >/dev/null
fi

if [ "$mode" = print ]; then
  if command -v kitty >/dev/null 2>&1; then
    echo "# one kitty, then one tab per seat:"
    "$python" "$snapshot" "$@" --print | sed -n '/^kitty /,$p'
  else
    echo "# kitty is not installed - ghostty fallback, one window per seat:"
    "$python" "$snapshot" "$@" --ghostty
  fi
  exit 0
fi

# One restore per boot. The hook can fire more than once (a shell restart re-runs it), and
# two restores would leave two of every seat.
boot_id=$(cat /proc/sys/kernel/random/boot_id 2>/dev/null || echo none)
if [ -z "$only" ] && [ -f "$marker" ] && [ "$(cat "$marker" 2>/dev/null)" = "$boot_id" ]; then
  echo "hive: layout already restored this boot ($boot_id); nothing to do"
  exit 0
fi

seat_count=1
if [ -z "$only" ]; then
  seat_count=$(grep -c '"designation"' "$layout_file")
fi
if command -v kitty >/dev/null 2>&1; then
  rm -f "$socket"
  # The host kitty is SEATLESS on purpose. `kitty -e <cmd>` exits when <cmd> exits and the
  # control socket dies with the process, so a seat riding in the host made that one seat's
  # health a liveness dependency for every other seat. Detached: the hook must not block the
  # desktop session waiting on a terminal.
  setsid sh -c "$("$python" "$snapshot" "$@" --kitty-start)" >/dev/null 2>&1 &
  # Wait until remote control actually ANSWERS, not merely until the socket file exists. Every
  # seat is now a `kitten @ launch` against this socket, so a socket that exists but is not yet
  # serving would fail all six launches at once (grok review, 2026-10-30).
  ready=""
  tries=0
  while [ "$tries" -lt 60 ]; do
    if kitten @ --to "unix:$socket" ls >/dev/null 2>&1; then ready=1; break; fi
    sleep 0.25
    tries=$((tries + 1))
  done
  if [ -z "$ready" ]; then
    echo "hive: kitty never answered on $socket; nothing was restored" >&2
    exit 1
  fi
  "$python" "$snapshot" "$@" --kitty-tabs | while IFS= read -r command; do
    sh -c "$command" >/dev/null 2>&1 || echo "hive: could not open one seat: $command" >&2
  done
  # Drop the host tab - matched by title, never by a missing env var, because a tab whose CLI
  # has not appeared yet looks seatless too. So the window ends up being nothing but seats.
  "$python" "$snapshot" "$@" --close-host | while IFS= read -r command; do
    sh -c "$command" >/dev/null 2>&1 || true
  done
  # Count what actually came up, print it, and keep a line of it. Silence is what let three
  # restore bugs live for days: a restore that cannot say what it opened is not finished.
  report=$("$python" "$snapshot" "$@" --verify 2>&1)
  status=$?
  echo "hive: ${report}"
  printf '%s  %s\n' "$(date -Is 2>/dev/null || date)" "$report" \
    >> "${HOME}/.megazword/hive-restore.log"
  if [ "$status" -ne 0 ]; then
    # No boot marker on a bad count, so an incomplete restore can still run again this boot.
    echo "hive: restore incomplete - leaving the boot marker unset so it can retry" >&2
    exit 1
  fi
else
  echo "hive: kitty is not installed - the tab grouping cannot be restored; opening windows" >&2
  "$python" "$snapshot" "$@" --ghostty | while IFS= read -r command; do
    setsid sh -c "$command" >/dev/null 2>&1 &
  done
  echo "hive: restored ${seat_count} seats as separate windows"
fi

if [ -z "$only" ]; then
  printf '%s' "$boot_id" > "$marker"
fi
